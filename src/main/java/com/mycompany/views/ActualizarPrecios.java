    private void jbActualizarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jbActualizarMouseClicked
     int fila = jTable1.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
            "Selecciona un registro de la tabla",
            "Aviso",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (txtNuevoPrecio.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Ingresa el nuevo precio",
            "Aviso",
            JOptionPane.WARNING_MESSAGE
        );
        txtNuevoPrecio.requestFocus();
        return;
    }

    try {
        // ===== Datos desde la tabla =====
        int idCompra = (int) modelo.getValueAt(fila, 0);
        int idDetalleCompra = (int) modelo.getValueAt(fila, 1);
        String idProducto = modelo.getValueAt(fila, 2).toString();
        double precioCompra = ((Number) modelo.getValueAt(fila, 4)).doubleValue();

        // ===== Datos desde la UI =====
        double precioAnterior = Double.parseDouble(txtPrecioAnterior.getText());
        double nuevoPrecio = Double.parseDouble(txtNuevoPrecio.getText());

        if (nuevoPrecio <= 0) {
            throw new NumberFormatException();
        }

        // ===== USO DEL MODELO (AQUÍ ESTÁ LA RESPUESTA A TU DUDA) =====
        precioActualizado pa = new precioActualizado();
        pa.setIdProducto(idProducto);
        pa.setPrecioAnterior(precioAnterior);
        pa.setPrecioCompra(precioCompra);
        pa.setNuevoPrecio(nuevoPrecio);
        pa.setIdCompra(idCompra);
        pa.setIdDetalleCompra(idDetalleCompra);
        pa.setFechaActualizacion(
            new java.sql.Timestamp(System.currentTimeMillis())
        );

        // ===== DAO =====
        DAOprecioActualizadoImp dao = new DAOprecioActualizadoImp();
        dao.conectar();
        dao.registrar(pa);
        dao.cerrarConexion();

        // ===== UI =====
        modelo.removeRow(fila);
        limpiarFormulario();

        JOptionPane.showMessageDialog(this,
            "Precio actualizado correctamente",
            "Éxito",
            JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Nuevo precio inválido",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        txtNuevoPrecio.requestFocus();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error al actualizar precio\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }    
    }//GEN-LAST:event_jbActualizarMouseClicked

