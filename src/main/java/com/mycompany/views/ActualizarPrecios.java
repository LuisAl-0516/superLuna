    private void inicializarTabla() {
    modelo = new DefaultTableModel(
        new String[]{
            "Id Compra",
            "Id Detalle",
            "Código",
            "Cantidad",
            "Precio Compra"
        }, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    jTable1.setModel(modelo);
}
    private void cargarPendientes() {
    try {
        modelo.setRowCount(0); // limpiar tabla

        DAOprecioActualizadoImp dao = new DAOprecioActualizadoImp();
        dao.conectar(); // si tu DAO hereda de Conexion

        for (detalleCompra d : dao.listarPreciosSinActualizar()) {
            modelo.addRow(new Object[]{
                d.getIdCompra(),
                d.getIdCompraDetalle(),
                d.getIdProducto(),
                d.getCantidad(),
                d.getPrecioUni()
            });
        }

        dao.cerrarConexion();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this,
            "Error al cargar pendientes\n" + e.getMessage(),
            "ERROR",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
